def _collect(bone, mat):
    """The vertices made since the last collect: bmesh wrappers and tags are not stable across
    operators, so new geometry is told apart by the int layer, which new vertices get as 0."""
    verts = [v for v in bm.verts if v[bone_layer] == 0]
    if bone not in BONE_NAMES:
        BONE_NAMES.append(bone)
    for v in verts:
        v[bone_layer] = BONE_NAMES.index(bone) + 1
    pw.assign_material_index(bm, verts, ORDER.index(mat))
    return verts


def block(bone, center, size, mat="visitor_stone", bevel=(0.016, 2), taper=None):
    """A box, optionally narrowed at its lower end (taper = factors for x and y), with its edges
    bevelled in `segments` steps; the bevel strip is shaded smooth so the edge reads rounded."""
    vs = pw.add_box(bm, center, size)
    if taper:
        cx, cy, cz = center
        for v in vs:
            if v.co.z < cz:
                v.co.x = cx + (v.co.x - cx) * taper[0]
                v.co.y = cy + (v.co.y - cy) * taper[1]
    if bevel and bevel[0] > 0:
        edges = list({e for v in vs for e in v.link_edges})
        res = bmesh.ops.bevel(bm, geom=edges, offset=bevel[0], offset_type="OFFSET", segments=bevel[1], profile=0.5, affect="EDGES", clamp_overlap=True)
        for f in res["faces"]:
            f.smooth = True
    return _collect(bone, mat)


def ball(bone, center, radius, mat="visitor_brass"):
    pw.add_ico(bm, center, radius, 2)
    verts = _collect(bone, mat)
    for v in verts:
        for f in v.link_faces:
            f.smooth = True
    return verts


def drum(bone, center, radius, length, axis, mat="visitor_brass", segments=14):
    """A short cylinder centred on `center` along the x or z axis: the hinge of a joint."""
    vs = pw.add_cone(bm, (0, 0, 0), radius, radius, length, segments=segments)
    if axis == "x":
        bmesh.ops.rotate(bm, verts=vs, cent=(0, 0, 0), matrix=Matrix.Rotation(math.radians(90), 3, "Y"))
        bmesh.ops.translate(bm, verts=vs, vec=Vector((center[0] - length / 2, center[1], center[2])))
    else:
        bmesh.ops.translate(bm, verts=vs, vec=Vector((center[0], center[1], center[2] - length / 2)))
    verts = _collect(bone, mat)
    for v in verts:
        for f in v.link_faces:
            f.normal_update()
            along = abs(f.normal.x) if axis == "x" else abs(f.normal.z)
            f.smooth = along < 0.9  # the caps stay flat
    return verts


def front_quad(bone, center, width, height, mat):
    """A quad with UVs facing -y, for a painted surface such as the screen or the badge."""
    hw, hh = width / 2, height / 2
    cx, cy, cz = center
    corners = [(cx - hw, cy, cz - hh), (cx + hw, cy, cz - hh), (cx + hw, cy, cz + hh), (cx - hw, cy, cz + hh)]
    vs = [bm.verts.new(c) for c in corners]
    face = bm.faces.new(vs)
    face.normal_update()
    if face.normal.y > 0:
        bmesh.ops.reverse_faces(bm, faces=[face])
    uvs = [(0, 0), (1, 0), (1, 1), (0, 1)]  # with the export to y-up this order reads the right way round from the front
    for loop in face.loops:
        k = vs.index(loop.vert)
        loop[uv_layer].uv = uvs[k]
    return _collect(bone, mat)


