def pose(frame, bone, fwd=0.0, roll=0.0, yaw=0.0, loc=None):
    """fwd swings the far end of the bone towards -y (the front): the top of an upright bone leans
    forward, the foot of a leg goes forward. roll turns about the depth axis, yaw about the vertical."""
    pb = rig.pose.bones[bone]
    angle_x = fwd if points_up[bone] else -fwd
    world = Euler((angle_x, roll, yaw), "XYZ").to_matrix()
    local = rest[bone].inverted() @ world @ rest[bone]
    pb.rotation_euler = local.to_euler("XYZ")
    pb.keyframe_insert("rotation_euler", frame=frame)
    if loc is not None:
        pb.location = Vector(loc)
        pb.keyframe_insert("location", frame=frame)


def clip(name, frames, fn, loop=True):
    action = bpy.data.actions.new(name)
    rig.animation_data_create()
    rig.animation_data.action = action
    for f in range(frames + (1 if loop else 0)):
        fn(f, f / frames)
    for fc in action.fcurves:
        for kp in fc.keyframe_points:
            kp.interpolation = "BEZIER"
    rig.animation_data.action = None
    track = rig.animation_data.nla_tracks.new()
    track.name = name
    track.strips.new(name, 0, action)
    return action


A_THIGH, B_SHIN = 0.36, 0.35  # hip to knee, knee to ankle
ANKLE_Z = 0.09
REACH = (A_THIGH + B_SHIN) * 0.995  # the leg never quite locks straight


def leg_ik(frame, side, ankle_fwd, ankle_z, hip_z, foot_pitch, toe_pitch):
    """Two-bone analytic IK in the sagittal plane: the ankle sits `ankle_fwd` metres ahead of the hip
    joint and `ankle_z` high with the hip at `hip_z`; the foot takes an absolute pitch (toe up
    positive) and the toe its own relative pitch (toe up positive)."""
    d_down = hip_z - ankle_z
    dist = min(math.hypot(ankle_fwd, d_down), REACH)
    cos_gamma = (A_THIGH * A_THIGH + dist * dist - B_SHIN * B_SHIN) / (2 * A_THIGH * dist)
    cos_knee = (A_THIGH * A_THIGH + B_SHIN * B_SHIN - dist * dist) / (2 * A_THIGH * B_SHIN)
    gamma = math.acos(max(-1.0, min(1.0, cos_gamma)))
    knee = math.pi - math.acos(max(-1.0, min(1.0, cos_knee)))
    thigh = math.atan2(ankle_fwd, d_down) + gamma
    pose(frame, f"thigh.{side}", fwd=thigh)
    pose(frame, f"shin.{side}", fwd=-knee)
    pose(frame, f"foot.{side}", fwd=foot_pitch - (thigh - knee))
    pose(frame, f"toe.{side}", fwd=-toe_pitch)  # the toe bone lies flat, so its positive turn is downward


def hermite(p0, p1, m0, m1, u):
    u2, u3 = u * u, u * u * u
    return (2 * u3 - 3 * u2 + 1) * p0 + (u3 - 2 * u2 + u) * m0 + (-2 * u3 + 3 * u2) * p1 + (u3 - u2) * m1


def smooth(u):
    u = max(0.0, min(1.0, u))
    return u * u * (3 - 2 * u)


def foot_cycle(u, speed, cycle, stance, contact_ahead, lift):
    """Where one ankle is through its cycle (u from 0 at heel contact), relative to the hip joint:
    forward offset, height, foot pitch and toe pitch. Planted through the stance (it moves back
    under the body at the walking speed), a Hermite arc through the swing whose end tangents match
    that speed, so nothing slides at toe-off or at contact; the heel rolls down over the first 18 %
    of the stance and lifts from 55 %, the toe staying flat on the ground."""
    travel = speed * stance * cycle
    f_contact = contact_ahead + travel / 2
    f_off = f_contact - travel
    if u < stance:
        w = u / stance
        fwd = f_contact - travel * w
        if w < 0.18:
            pitch = math.radians(15) * (1 - w / 0.18)
        elif w < 0.55:
            pitch = 0.0
        else:
            pitch = -math.radians(32) * smooth((w - 0.55) / 0.45)
        z = ANKLE_Z + 0.09 * math.sin(abs(pitch))
        toe = max(0.0, -pitch)
    else:
        w = (u - stance) / (1 - stance)
        tangent = -speed * (1 - stance) * cycle
        fwd = hermite(f_off, f_contact, tangent, tangent, w)
        z = ANKLE_Z + 0.09 * math.sin(math.radians(32)) * (1 - smooth(w * 2)) + lift * math.sin(math.pi * w) ** 0.8
        pitch = -math.radians(32) + (math.radians(32) + math.radians(15)) * smooth((w - 0.1) / 0.8)
        toe = max(0.0, -pitch) * (1 - 0.7 * smooth(w * 1.5))
    return fwd, z, pitch, toe


def hip_floor(t, speed, cycle, stance, contact_ahead, lift):
    """The highest the hips can sit at t with every planted foot reachable (ground lock)."""
    floors = []
    for offset in (0.0, 0.5):
        u = (t + offset) % 1.0
        if u < stance:
            fwd, z, _pitch, _toe = foot_cycle(u, speed, cycle, stance, contact_ahead, lift)
            floors.append(z + math.sqrt(max(0.0, REACH * REACH - fwd * fwd)))
    return min(floors) if floors else None


def hip_height(t, speed, cycle, stance, contact_ahead, lift, hip_nominal, bob_top):
    """A smooth bob: a cosine with two dips per cycle whose lowest points are the ground lock at
    the contacts and whose crest sits at `bob_top` (passing, or mid-flight when running), never
    above what the planted legs allow."""
    # the trough sits where the planted legs allow least (the contact), the crest a quarter later
    samples = [(hip_floor(u / 100, speed, cycle, stance, contact_ahead, lift), u / 100) for u in range(0, int(stance * 100) + 1)]
    low, trough = min((v, u) for v, u in samples if v is not None)
    top = hip_nominal
    h = top - (top - low) * (1 - math.cos(4 * math.pi * (t - trough - 0.25))) / 2
    floor = hip_floor(t, speed, cycle, stance, contact_ahead, lift)
    return min(h, floor) if floor is not None else h


def gait(f, t, speed, cycle, stance, contact_ahead, lift, hip_nominal, bob_top, arms, elbow0, elbow1, lean, sway, twist, lag):
    """One cycle of a gait with the left heel striking at t = 0 and the right half a cycle later.
    The hips sit as high as the planted legs allow (ground lock), which gives the dip at each
    contact and the rise at passing, or on a parabola during a flight phase; the pelvis shifts and
    rolls over the stance leg, the chest counter-rotates one frame behind it, the arms swing
    against the legs with the elbow bending as the arm comes forward, and the antenna lags."""
    p = math.tau * t
    feet = {"L": foot_cycle(t % 1.0, speed, cycle, stance, contact_ahead, lift), "R": foot_cycle((t + 0.5) % 1.0, speed, cycle, stance, contact_ahead, lift)}
    hip_z = hip_height(t % 1.0, speed, cycle, stance, contact_ahead, lift, hip_nominal, bob_top)
    for side, (fwd, z, pitch, toe) in feet.items():
        leg_ik(f, side, fwd, z, hip_z, pitch, toe)
    # the pelvis: over the stance leg, rolling and turning with it; the chest answers a frame late
    lat = sway * math.sin(p)
    pose(f, "hips", fwd=lean * 0.3, roll=-0.03 * math.sin(p), yaw=-twist * math.cos(p), loc=(lat, hip_z - 0.80, 0.0))
    pose(f, "spine", fwd=lean * 0.3, yaw=twist * math.cos(p - lag), roll=0.03 * math.sin(p - lag))
    pose(f, "chest", fwd=lean * 0.4, yaw=twist * math.cos(p - lag), roll=0.035 * math.sin(p - lag))
    pose(f, "neck", fwd=-lean * 0.3)
    pose(f, "head", fwd=-lean * 0.5 + 0.03 * max(0.0, math.sin(2 * p - 0.6)), yaw=-twist * 0.8 * math.cos(p - 2 * lag), roll=-0.02 * math.sin(p - 2 * lag))
    pose(f, "antenna", fwd=-0.08 * max(0.0, math.sin(2 * p - 1.4)), roll=0.12 * math.sin(p - 3 * lag))
    # the arms, against the legs: the left leg is forward at t = 0, so the left arm is back
    for side, sgn in (("L", 1.0), ("R", -1.0)):
        swing = -sgn * math.cos(p - lag)  # +1 when this arm is forward
        pose(f, f"shoulder.{side}", yaw=sgn * 0.08 * swing, fwd=0.03 * max(0.0, swing))
        pose(f, f"upper_arm.{side}", fwd=arms * swing - 0.05, roll=sgn * 0.06, yaw=-sgn * 0.12 * max(0.0, swing) if arms > 0.5 else 0.0)
        bend = elbow0 + elbow1 * 0.5 * (1 - sgn * math.cos(p - 2 * lag))
        pose(f, f"forearm.{side}", fwd=bend)
        pose(f, f"hand.{side}", fwd=0.1 + 0.1 * sgn * math.cos(p - 3 * lag))


